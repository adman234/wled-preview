export const DYNAMIC_PALETTES = { 0: 'Default', 1: 'Random Cycle', 2: 'Color 1', 3: 'Colors 1&2', 4: 'Color Gradient', 5: 'Colors Only' };

export function paletteName(id) {
  if (DYNAMIC_PALETTES[id]) return DYNAMIC_PALETTES[id];
  return PALETTES[id] ? PALETTES[id][0] : `Palette #${id}`;
}

export const isKnownPalette = (id) => id in DYNAMIC_PALETTES || id in PALETTES;

export function sampleStops(stops, idx) {
  // idx 0-255 (wraps), linear interpolation between stops
  const x = ((idx % 256) + 256) % 256;
  let a = stops[0], b = stops[stops.length - 1];
  for (let i = 0; i < stops.length - 1; i++) {
    if (x >= stops[i][0] && x <= stops[i + 1][0]) { a = stops[i]; b = stops[i + 1]; break; }
  }
  const span = b[0] - a[0] || 1;
  const f = Math.min(1, Math.max(0, (x - a[0]) / span));
  return [a[1] + (b[1] - a[1]) * f, a[2] + (b[2] - a[2]) * f, a[3] + (b[3] - a[3]) * f];
}
